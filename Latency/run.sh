#!/usr/bin/env bash
# 一键全跑(单卡部分), 固定卡 3。结果带时间戳存 results/
#   DEV=5 ./run.sh   换卡
# 跨卡(NVLink)那组用 ./p2p.sh, 默认卡 6->7
set -euo pipefail
cd "$(dirname "$0")"
DEV=${DEV:-3}
make -s all
mkdir -p results
STAMP=$(date +%Y%m%d-%H%M%S)
OUT=results/all-gpu${DEV}-${STAMP}.txt
{
  echo "###################################################################"
  echo "#  Hopper 延迟微基准套件 —— 全量结果"
  echo "#  $(date -Is)   主机=$(hostname)   卡=${DEV}"
  echo "###################################################################"
  nvidia-smi --query-gpu=index,name,pstate,clocks.sm,clocks.mem,temperature.gpu,utilization.gpu,memory.used \
             --format=csv -i "${DEV}"
  nvcc --version | tail -1
  echo
  echo "###################################################################"
  echo "#  第一类: 存储层次 —— 读延迟"
  echo "###################################################################"
  ./01_mem_read --dev "${DEV}"
  echo
  echo "###################################################################"
  echo "#  第一类: 存储层次 —— 写延迟"
  echo "###################################################################"
  ./02_mem_write --dev "${DEV}"
  echo
  echo "###################################################################"
  echo "#  第一类: 存储层次 —— 容量台阶 / L2 分区 / NCU 归属验证"
  echo "###################################################################"
  ./03_mem_levels --dev "${DEV}" --all
  echo
  echo "###################################################################"
  echo "#  第二类: 指令延迟 —— 标量指令"
  echo "###################################################################"
  ./05_inst --dev "${DEV}"
  echo
  echo "###################################################################"
  echo "#  第二类: 指令延迟 —— tensor core"
  echo "###################################################################"
  ./06_tensor --dev "${DEV}"
  echo
  echo "###################################################################"
  echo "#  第三类: 同步与一致性"
  echo "###################################################################"
  ./07_sync --dev "${DEV}"
  echo
  echo "###################################################################"
  echo "#  第四类: 异步数据搬运 (cp.async / TMA)"
  echo "###################################################################"
  ./08_async_copy --dev "${DEV}"
} 2>&1 | tee "${OUT}"
echo
echo "延迟直方图峰值分析:"; ./analyze.py "${OUT}" || true
echo; echo "已保存 -> ${OUT}"
